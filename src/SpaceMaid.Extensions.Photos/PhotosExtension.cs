using System.Windows;
using SpaceMaid.Core.Analysis;
using SpaceMaid.Core.Optimization;
using SpaceMaid.Extensions.Contracts;

namespace SpaceMaid.Extensions.Photos;

public sealed class PhotosExtension : ISpaceMaidExtension, IOpportunityExtension
{
    private IExtensionHost? _host;
    private PhotoCatalog? _catalog;
    private PhotosView? _view;
    private readonly CancellationTokenSource _lifetime = new();
    public ExtensionDescriptor Descriptor => new("space-maid.photos", "Photos", "1.0.0");
    public async Task InitializeAsync(IExtensionHost host, CancellationToken token)
    {
        _host = host;
        _catalog = new PhotoCatalog(host.DataDirectory);
        var native = await Task.Run(_catalog.Initialize, token);
        host.Log("photos-catalog-ready", new { ManagedSqlite = typeof(Microsoft.Data.Sqlite.SqliteConnection).Assembly.GetName().Version?.ToString(), NativeSqlite = native, Schema = 1 });
    }
    public FrameworkElement CreateView()
    {
        if (_host is null || _catalog is null) throw new InvalidOperationException("Photos must be initialized before creating its view.");
        return _view ??= new PhotosView(_host, _catalog, _lifetime.Token);
    }
    public OpportunityAnalysis Analyze(IOpportunityInventory inventory, CancellationToken token)
    {
        var findings = new List<Opportunity>();
        string? cache = _host is null ? null : Path.Join(_host.CacheDirectory, "thumbnails-v1");
        for (int i = 0; cache is not null && i < inventory.FileCount; i++)
        {
            token.ThrowIfCancellationRequested();
            if (!inventory.IsDirectory(i) || !string.Equals(inventory.PathForFile(i), cache, StringComparison.OrdinalIgnoreCase)) continue;
            findings.Add(new(i, "Photo preview cache", "Tool caches", cache, inventory.LogicalSize(i), inventory.AllocatedSize(i),
                "Previews generated by Space Maid.", "Original photos and catalog records are kept.", "Previews regenerate when photos are opened.", false)
            { RuleId = "photo-thumbnails", Appearance = OpportunityAppearance.Cache, IsRegeneratable = true,
                AutomaticCleanup = new("photo-thumbnails", "Photo previews", "Space Maid regenerates previews from available originals. Offline originals need to be available again.", [".png"]) });
            break;
        }
        return new(findings.AsReadOnly(), new([], []));
    }
    public async ValueTask DisposeAsync()
    {
        _lifetime.Cancel();
        if (_view is not null) await _view.ShutdownAsync();
        _catalog?.Dispose(); _lifetime.Dispose();
    }
}
